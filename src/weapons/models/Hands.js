class SkinBuilder {
  constructor(flip) {
    this.pos = [];
    this.nrm = [];
    this.uv = [];
    this.col = [];
    this.si = [];
    this.sw = [];
    this.idx = [];
    this.flip = flip ? -1 : 1;
  }

  vertex(p, n, u, v, bones, weights, shade = 1) {
    this.pos.push(p.x, p.y, p.z);
    this.nrm.push(n.x, n.y, n.z);
    this.uv.push(u, v);
    this.col.push(shade, shade, shade);
    this.si.push(bones[0] | 0, bones[1] | 0, bones[2] | 0, bones[3] | 0);
    this.sw.push(weights[0] || 0, weights[1] || 0, weights[2] || 0, weights[3] || 0);
    return this.pos.length / 3 - 1;
  }

  quad(a, b, c, d) {
    if (this.flip < 0) { this.tri(a, c, b); this.tri(a, d, c); }
    else { this.tri(a, b, c); this.tri(a, c, d); }
  }

  tri(a, b, c) { this.idx.push(a, b, c); }

  build() {
    const g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.Float32BufferAttribute(this.pos, 3));
    g.setAttribute('normal', new THREE.Float32BufferAttribute(this.nrm, 3));
    g.setAttribute('uv', new THREE.Float32BufferAttribute(this.uv, 2));
    g.setAttribute('color', new THREE.Float32BufferAttribute(this.col, 3));
    g.setAttribute('skinIndex', new THREE.Uint16BufferAttribute(this.si, 4));
    g.setAttribute('skinWeight', new THREE.Float32BufferAttribute(this.sw, 4));
    g.setIndex(this.idx);
    g.computeVertexNormals();
    g.computeBoundingSphere();
    return g;
  }

  get empty() { return this.idx.length === 0; }
}

const _up = new THREE.Vector3(0, 1, 0);
const _alt = new THREE.Vector3(1, 0, 0);

/** Superelliptical ring — rounded-rectangle cross-section, not a circle. */
function ringPoint(out, a, rx, ry, n) {
  const c = Math.cos(a), s = Math.sin(a);
  const p = 2 / n;
  out.set(
    Math.sign(c) * Math.pow(Math.abs(c), p) * rx,
    Math.sign(s) * Math.pow(Math.abs(s), p) * ry,
    0,
  );
  return out;
}

/**
 * Sweep a tube along a joint polyline with per-ring radii and blended skin
 * weights. `joints` is [{p:Vector3, bone:index}] and `radii` is [[rx,ry], ...]
 * one per joint (plus the tip).
 */
function sweep(builder, joints, radii, opts = {}) {
  const segs = opts.segments ?? 9;
  const nExp = opts.exponent ?? 3.2;
  const sub = opts.sub ?? 3;
  const shade = opts.shade ?? 1;
  const rings = [];

  const dir = new THREE.Vector3();
  const nx = new THREE.Vector3();
  const ny = new THREE.Vector3();
  const tmp = new THREE.Vector3();
  const pt = new THREE.Vector3();
  let arc = 0;

  for (let i = 0; i < joints.length - 1; i++) {
    const a = joints[i], b = joints[i + 1];
    dir.subVectors(b.p, a.p);
    const segLen = dir.length() || 1e-5;
    dir.multiplyScalar(1 / segLen);
    const ref = Math.abs(dir.dot(_up)) > 0.92 ? _alt : _up;
    nx.crossVectors(ref, dir).normalize();
    ny.crossVectors(dir, nx).normalize();

    const count = i === joints.length - 2 ? sub + 1 : sub;
    for (let s = 0; s < count; s++) {
      const u = s / sub;
      const t = i + u;
      // blend the two bones across the joint so the crease folds smoothly
      let w0 = 1, b0 = a.bone, b1 = a.bone;
      if (u < 0.34 && i > 0) {
        b1 = joints[i - 1].bone;
        w0 = 0.55 + (u / 0.34) * 0.45;
      }
      const r0 = radii[i], r1 = radii[i + 1];
      let rx = r0[0] + (r1[0] - r0[0]) * u;
      let ry = r0[1] + (r1[1] - r0[1]) * u;
      // knuckle swell at the head of each bone
      if (opts.knuckles && u < 0.3 && i > 0) {
        const k = 1 + 0.16 * (1 - u / 0.3);
        rx *= k; ry *= k;
      }
      const ring = [];
      const vcoord = arc + u * segLen;
      for (let k = 0; k < segs; k++) {
        const ang = (k / segs) * Math.PI * 2;
        ringPoint(pt, ang, rx, ry, nExp);
        tmp.copy(a.p)
          .addScaledVector(dir, u * segLen)
          .addScaledVector(nx, pt.x)
          .addScaledVector(ny, pt.y);
        const n = tmp.clone().sub(
          new THREE.Vector3().copy(a.p).addScaledVector(dir, u * segLen),
        ).normalize();
        // palm side sits in shadow, knuckle side catches light
        const sh = shade * (0.82 + 0.18 * (0.5 - 0.5 * Math.sin(ang)));
        ring.push(builder.vertex(tmp, n, k / segs, vcoord * 12, [b0, b1, 0, 0], [w0, 1 - w0, 0, 0], sh));
      }
      rings.push(ring);
    }
    arc += segLen;
  }

  for (let i = 0; i < rings.length - 1; i++) {
    const A = rings[i], B = rings[i + 1];
    for (let k = 0; k < segs; k++) {
      const k2 = (k + 1) % segs;
      builder.quad(A[k], A[k2], B[k2], B[k]);
    }
  }

  // tip cap
  if (opts.cap !== false) {
    const last = rings[rings.length - 1];
    const tip = joints[joints.length - 1];
    const tipDir = new THREE.Vector3().subVectors(tip.p, joints[joints.length - 2].p).normalize();
    const r = radii[radii.length - 1];
    const centre = tip.p.clone().addScaledVector(tipDir, Math.max(r[0], r[1]) * 0.62);
    const ci = builder.vertex(centre, tipDir, 0.5, 0, [tip.bone, tip.bone, 0, 0], [1, 0, 0, 0], shade * 0.95);
    for (let k = 0; k < segs; k++) {
      const k2 = (k + 1) % segs;
      if (builder.flip < 0) builder.tri(last[k], ci, last[k2]);
      else builder.tri(last[k], last[k2], ci);
    }
  }
  return rings;
}

/** Append a plain BufferGeometry rigidly weighted to one bone. */
function appendRigid(builder, geom, matrix, bone, shade = 1) {
  const g = geom.index ? geom.toNonIndexed() : geom;
  if (!g.attributes.normal) g.computeVertexNormals();
  g.applyMatrix4(matrix);
  const pos = g.attributes.position;
  const nrm = g.attributes.normal;
  const p = new THREE.Vector3();
  const n = new THREE.Vector3();
  const base = builder.pos.length / 3;
  for (let i = 0; i < pos.count; i++) {
    p.fromBufferAttribute(pos, i);
    n.fromBufferAttribute(nrm, i);
    builder.vertex(p, n, p.x * 24, p.z * 24, [bone, bone, 0, 0], [1, 0, 0, 0], shade);
  }
  for (let i = 0; i < pos.count; i += 3) {
    if (builder.flip < 0) builder.tri(base + i, base + i + 2, base + i + 1);
    else builder.tri(base + i, base + i + 1, base + i + 2);
  }
  g.dispose?.();
}

