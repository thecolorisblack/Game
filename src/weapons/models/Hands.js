/**
 * @param {Object} palette   from models/Palette.js
 * @param {Object} opts      {side:'right'|'left', forearm:number, sleeve:boolean}
 * @returns {{root:THREE.Object3D, bones:Object, skeleton:THREE.Skeleton,
 *            meshes:THREE.SkinnedMesh[], applyPose:Function}}
 */
export function buildHand(palette, opts = {}) {
  // The tables above describe a LEFT hand (thumb toward -X, dorsal +Y, fingers
  // +Z is a left-handed triple); the right hand is the mirror, which also means
  // its triangle winding has to be reversed.
  const left = opts.side === 'left';
  const sx = left ? 1 : -1;
  const mirrored = sx < 0;
  const forearmLen = opts.forearm ?? 0.300;

  /* ---- skeleton ---- */
  const bones = {};
  const list = [];
  const mk = (name, parent, p) => {
    const b = new THREE.Bone();
    b.name = name;
    b.position.set(p[0] * sx, p[1], p[2]);
    const r = REST[name] || [0, 0, 0];
    // -r[0]: authored flexion is negative, the skeleton flexes on +X
    b.rotation.set(-r[0], r[1] * sx, r[2] * sx);
    if (parent) parent.add(b);
    bones[name] = b;
    b.userData.index = list.length;
    list.push(b);
    return b;
  };

  // The wrist is the root: the socket places the *hand* on the weapon, and the
  // forearm hangs off it as a sibling of the palm so it can be aimed back at
  // the shoulder without dragging the grip out of position.
  const wrist = mk('wrist', null, [0, 0, 0]);
  const forearm = mk('forearm', wrist, [0, 0, 0]);
  const palm = mk('palm', wrist, [0, 0, 0]);

  for (const f of FINGERS) {
    let parent = palm;
    let base = [f.x, 0, f.z];
    for (let i = 0; i < 3; i++) {
      const name = `${f.name}${i + 1}`;
      const b = mk(name, parent, i === 0 ? base : [0, 0, f.seg[i - 1]]);
      if (i === 0) b.rotation.y = f.spread * sx + (REST[name]?.[1] ?? 0) * sx;
      parent = b;
    }
  }
  {
    let parent = palm;
    for (let i = 0; i < 3; i++) {
      const name = `thumb${i + 1}`;
      parent = mk(name, parent, i === 0 ? THUMB.base : [0, 0, THUMB.seg[i - 1]]);
    }
  }

  wrist.updateMatrixWorld(true);
  const skeleton = new THREE.Skeleton(list);

  const wp = (b) => new THREE.Vector3().setFromMatrixPosition(b.matrixWorld);
  const bi = (name) => bones[name].userData.index;

  /* ---- skin ---- */
  const skin = new SkinBuilder(mirrored);
  const pads = new SkinBuilder(mirrored);
  const strap = new SkinBuilder(mirrored);

  // forearm + wrist: one long taper into the hand, authored down the bone's -Z
  const at = (z) => new THREE.Vector3(0, 0, z);
  sweep(skin, [
    { p: at(-forearmLen), bone: bi('forearm') },
    { p: at(-forearmLen * 0.62), bone: bi('forearm') },
    { p: at(-forearmLen * 0.22), bone: bi('forearm') },
    { p: at(-0.004), bone: bi('wrist') },
  ], [
    [0.0480, 0.0455], [0.0430, 0.0398], [0.0348, 0.0312], [0.0312, 0.0268],
  ], { segments: 12, exponent: 2.6, sub: 3, cap: false, shade: 0.94 });

  // palm block: a swept slab from the wrist to the knuckle row
  const knuckleMid = wp(bones.middle1);
  sweep(skin, [
    { p: wp(wrist), bone: bi('wrist') },
    { p: wp(wrist).clone().lerp(knuckleMid, 0.34), bone: bi('palm') },
    { p: wp(wrist).clone().lerp(knuckleMid, 0.72), bone: bi('palm') },
    { p: knuckleMid.clone().addScaledVector(new THREE.Vector3(0, 0, 1), 0.004), bone: bi('palm') },
  ], [
    [0.0312, 0.0268], [0.0392, 0.0224], [0.0430, 0.0192], [0.0424, 0.0176],
  ], { segments: 14, exponent: 3.8, sub: 3, cap: false, shade: 1.0 });

  // thenar eminence (the muscle at the base of the thumb) — asymmetric bulge
  {
    const m = new THREE.Matrix4().compose(
      wp(bones.thumb1).clone().lerp(wp(wrist), 0.32).add(new THREE.Vector3(0, -0.004, 0)),
      new THREE.Quaternion().setFromEuler(new THREE.Euler(0.1, 0.35 * sx, 0)),
      new THREE.Vector3(1, 1, 1),
    );
    appendRigid(skin, chamferBox(0.024, 0.026, 0.048, 0.008, { curveSegments: 3 }), m, bi('palm'), 0.98);
  }

  // fingers
  for (const f of FINGERS) {
    const j = [];
    const r = [];
    for (let i = 0; i < 3; i++) {
      j.push({ p: wp(bones[`${f.name}${i + 1}`]), bone: bi(`${f.name}${i + 1}`) });
      r.push([f.r[i], f.r[i] * 0.88]);
    }
    const tipBone = bones[`${f.name}3`];
    const tip = new THREE.Vector3(0, 0, f.seg[2]).applyMatrix4(tipBone.matrixWorld);
    j.push({ p: tip, bone: bi(`${f.name}3`) });
    r.push([f.r[3], f.r[3] * 0.86]);
    sweep(skin, j, r, { segments: 9, exponent: 3.0, sub: 3, knuckles: true, shade: 1.0 });
  }

  // thumb
  {
    const j = [];
    const r = [];
    for (let i = 0; i < 3; i++) {
      j.push({ p: wp(bones[`thumb${i + 1}`]), bone: bi(`thumb${i + 1}`) });
      r.push([THUMB.r[i], THUMB.r[i] * 0.86]);
    }
    const tip = new THREE.Vector3(0, 0, THUMB.seg[2]).applyMatrix4(bones.thumb3.matrixWorld);
    j.push({ p: tip, bone: bi('thumb3') });
    r.push([THUMB.r[3], THUMB.r[3] * 0.84]);
    sweep(skin, j, r, { segments: 9, exponent: 3.0, sub: 3, knuckles: true, shade: 0.98 });
  }

  /* ---- glove hard parts ---- */
  // knuckle armour: one moulded pad per proximal finger bone
  for (const f of FINGERS) {
    const b = bones[`${f.name}1`];
    const m = new THREE.Matrix4().compose(
      wp(b).clone().add(new THREE.Vector3(0, f.r[0] * 0.78, 0.004)),
      new THREE.Quaternion().setFromEuler(new THREE.Euler(-0.2, 0, 0)),
      new THREE.Vector3(1, 1, 1),
    );
    appendRigid(pads, chamferBox(f.r[0] * 1.85, 0.0052, 0.0180, 0.0018, { curveSegments: 3 }), m, bi(`${f.name}1`), 1.0);
  }
  // dorsal plate across the back of the hand
  {
    const m = new THREE.Matrix4().compose(
      wp(wrist).clone().lerp(knuckleMid, 0.52).add(new THREE.Vector3(0, 0.0192, 0)),
      new THREE.Quaternion().setFromEuler(new THREE.Euler(-0.05, 0, 0)),
      new THREE.Vector3(1, 1, 1),
    );
    appendRigid(pads, chamferBox(0.0640, 0.0050, 0.0520, 0.0040, { curveSegments: 3 }), m, bi('palm'), 1.0);
    const m2 = new THREE.Matrix4().compose(
      wp(wrist).clone().lerp(knuckleMid, 0.52).add(new THREE.Vector3(0, 0.0224, 0)),
      new THREE.Quaternion(),
      new THREE.Vector3(1, 1, 1),
    );
    appendRigid(pads, chamferBox(0.0300, 0.0028, 0.0300, 0.0026, { curveSegments: 3 }), m2, bi('palm'), 1.06);
  }
  // palm grip patch (the rubberised panel that actually touches the weapon)
  {
    const m = new THREE.Matrix4().compose(
      wp(wrist).clone().lerp(knuckleMid, 0.55).add(new THREE.Vector3(0, -0.0186, 0)),
      new THREE.Quaternion(),
      new THREE.Vector3(1, 1, 1),
    );
    appendRigid(pads, chamferBox(0.0560, 0.0034, 0.0620, 0.0022, { curveSegments: 3 }), m, bi('palm'), 0.86);
  }

  /* ---- cuff + sleeve ---- */
  const cuffAt = at(-0.058);
  {
    const m = new THREE.Matrix4().compose(cuffAt, new THREE.Quaternion(), new THREE.Vector3(1, 1, 1));
    appendRigid(strap, chamferBox(0.0760, 0.0700, 0.0300, 0.0090, { curveSegments: 4 }), m, bi('forearm'), 1.0);
    const buckle = new THREE.Matrix4().compose(
      cuffAt.clone().add(new THREE.Vector3(0, 0.0330, 0.0)),
      new THREE.Quaternion(),
      new THREE.Vector3(1, 1, 1),
    );
    appendRigid(strap, chamferBox(0.0250, 0.0060, 0.0210, 0.0020, { curveSegments: 3 }), buckle, bi('forearm'), 1.1);
  }
  if (opts.sleeve !== false) {
    sweep(strap, [
      { p: at(-forearmLen - 0.07), bone: bi('forearm') },
      { p: at(-forearmLen * 0.86), bone: bi('forearm') },
      { p: at(-forearmLen * 0.52), bone: bi('forearm') },
      { p: at(-0.088), bone: bi('forearm') },
    ], [
      [0.0640, 0.0620], [0.0590, 0.0562], [0.0512, 0.0486], [0.0448, 0.0420],
    ], { segments: 14, exponent: 2.4, sub: 2, cap: false, shade: 0.92 });
  }

  /* ---- meshes ---- */
  const root = new THREE.Object3D();
  root.name = left ? 'handLeft' : 'handRight';
  root.add(wrist);

  const meshes = [];
  const mkMesh = (builder, material, name) => {
    if (builder.empty) return null;
    const mesh = new THREE.SkinnedMesh(builder.build(), material);
    mesh.name = name;
    mesh.frustumCulled = false;
    mesh.castShadow = false;
    mesh.receiveShadow = false;
    mesh.bind(skeleton, new THREE.Matrix4());
    root.add(mesh);
    meshes.push(mesh);
    return mesh;
  };
  mkMesh(skin, palette.glove, 'glove');
  mkMesh(pads, palette.glovePad, 'glovePads');
  mkMesh(strap, palette.webbing, 'cuff');

  /* ---- posing ---- */
  const targets = new Map();   // bone -> Quaternion
  const _eu = new THREE.Euler();
  const _qt = new THREE.Quaternion();

  function poseQuat(name, pose) {
    const r = (pose && pose[name]) || REST[name] || [0, 0, 0];
    let y = r[1] * sx;
    let z = r[2] * sx;
    // finger spread is baked per-finger and must survive posing
    for (const f of FINGERS) if (name === `${f.name}1`) y += f.spread * sx;
    _eu.set(-r[0], y, z, 'XYZ');
    return _qt.setFromEuler(_eu).clone();
  }

  /**
   * Blend the skeleton toward a named pose.
   * @param {string} name  key in HAND_POSES
   * @param {number} t     0..1 blend factor applied this frame
   */
  function applyPose(name, t = 1) {
    const pose = HAND_POSES[name] || HAND_POSES.rest;
    for (const b of list) {
      if (b.name === 'forearm' || b.name === 'wrist') continue;
      let q = targets.get(b.name);
      if (!q) { q = new THREE.Quaternion(); targets.set(b.name, q); }
      q.copy(poseQuat(b.name, pose));
      b.quaternion.slerp(q, THREE.MathUtils.clamp(t, 0, 1));
    }
  }

  /** Snap instantly, used on equip and by the capture harness. */
  function setPose(name) { applyPose(name, 1); }

  /**
   * Aim the forearm back toward the shoulder without disturbing the grip.
   * The forearm bone shares the hand root's frame and its mesh is built on the
   * axis, so these angles are *not* mirrored — each hand is aimed explicitly.
   */
  function setForearm(x, y, z) {
    bones.forearm.rotation.set(x, y, z);
  }

  setPose('rest');

  return {
    root, bones, skeleton, meshes, applyPose, setPose, setForearm,
    side: left ? 'left' : 'right',
  };
}
