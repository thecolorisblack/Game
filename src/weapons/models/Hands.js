/**
 * Procedural first-person arms.
 *
 * Most browser shooters ship a floating gun and hope nobody notices. They do:
 * absent hands are the single most obvious "this is a demo" tell in a
 * first-person frame. So this builds a real hand — a nineteen-bone skeleton
 * (four fingers x 3, thumb x 3, palm, wrist, forearm), swept-tube geometry with
 * superelliptical cross-sections so the fingers read as gloved rather than as
 * sausages, knuckle armour, a cuff and a sleeve — and skins it with blended
 * weights across each joint so the creases fold instead of pinching.
 *
 * Canonical build frame (right hand): fingers along +Z, palm faces -Y, thumb
 * toward -X. The left hand is generated by mirroring X and flipping winding, so
 * both hands share one authoring path.
 */

